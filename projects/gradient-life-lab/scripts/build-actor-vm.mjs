// Browser output is generated from the shared RPG VM; never maintain a second VM.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
const root = new URL('../../../prototyping/actor-vm/', import.meta.url);
const output = new URL('../public/actor-vm/', import.meta.url);
const check = process.argv.includes('--check');
async function emit(name, source) {
  const target = new URL(name, output);
  if (check) {
    if (await readFile(target, 'utf8') !== source) throw new Error(`Stale generated VM: ${name}`);
  } else { await mkdir(output, { recursive: true }); await writeFile(target, source); }
}
const header = '// Generated by scripts/build-actor-vm.mjs from the shared RPG VM.\n';
await emit('machine.mjs', header + ts.transpileModule(
  (await readFile(new URL('machine.ts', root), 'utf8')).replace('./vendor/decoder.cjs', './decoder.mjs'),
  { compilerOptions: { target: ts.ScriptTarget.ES2023, module: ts.ModuleKind.ES2022 } }).outputText);
for (const name of ['alu', 'decoder', 'constants', 'utils']) {
  let code = await readFile(new URL(`vendor/${name}.cjs`, root), 'utf8');
  code = code.replace(/const arithmetic = require\('\.\/alu.cjs'\);/, "import arithmetic from './alu.mjs';")
    .replace(/const \{ splitInstruction \} = require\('\.\/utils.cjs'\);/, "import { splitInstruction } from './utils.mjs';")
    .replace(/const (\{[\s\S]*?\}) = require\('\.\/constants.cjs'\);/, "import constants from './constants.mjs';\nconst $1 = constants;")
    .replace('module.exports =', 'export default').replace('exports.splitInstruction =', 'export const splitInstruction =');
  await emit(`${name}.mjs`, header + code);
}
await emit('LICENSE', await readFile(new URL('vendor/LICENSE', root), 'utf8'));
console.log(check ? 'Shared browser VM is current.' : `Generated shared browser VM at ${fileURLToPath(output)}`);
